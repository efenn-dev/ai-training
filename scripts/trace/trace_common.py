def now_iso() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def ensure_trace_dirs() -> None:
    for subdir in TRACE_SUBDIRS:
        (TRACE_ROOT / subdir).mkdir(parents=True, exist_ok=True)


def safe_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8", errors="replace")).hexdigest()[:16]


def scrub_text(text: str, max_chars: int = 120_000) -> tuple[str, int]:
    redactions = 0
    scrubbed = text
    if len(scrubbed) > max_chars:
        scrubbed = scrubbed[:max_chars] + "\n[TRUNCATED]"
        redactions += 1
    for pattern in SECRET_PATTERNS:
        new = pattern.sub("[REDACTED_SECRET]", scrubbed)
        if new != scrubbed:
            redactions += 1
            scrubbed = new
    for pattern, repl in [(WINDOWS_USER_PATH, r"C:\Users\USER"), (WSL_USER_PATH, "/home/USER"), (MNT_USER_PATH, "/mnt/DRIVE/Users/USER")]:
        new = pattern.sub(lambda _m, repl=repl: repl, scrubbed)
        if new != scrubbed:
            redactions += 1
            scrubbed = new
    if "base64" in scrubbed and len(scrubbed) > 2000:
        scrubbed = "[REDACTED_LARGE_BASE64_PAYLOAD]"
        redactions += 1
    return scrubbed, redactions


def scrub_obj(obj: Any) -> tuple[Any, int]:
    if isinstance(obj, str):
        return scrub_text(obj)
    if isinstance(obj, list):
        total = 0
        out = []
        for item in obj:
            cleaned, count = scrub_obj(item)
            out.append(cleaned)
            total += count
        return out, total
    if isinstance(obj, dict):
        total = 0
        out = {}
        for key, value in obj.items():
            cleaned, count = scrub_obj(value)
            out[key] = cleaned
            total += count
        return out, total
    return obj, 0


def append_jsonl(path: Path, row: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def append_trace_event(provider: str, event: dict[str, Any], run_id: str = "manual") -> Path:
    ensure_trace_dirs()
    cleaned, redactions = scrub_obj(event)
    envelope = {
        "schema_version": "agent-trace-event-v1",
        "trace_id": f"trace-{safe_hash(json.dumps(cleaned, sort_keys=True, default=str))}",
        "provider": provider,
        "run_id": run_id,
        "captured_at": now_iso(),
        "redaction_count": redactions,
        "event": cleaned,
    }
    path = TRACE_ROOT / "raw" / provider / run_id / "events.jsonl"
    append_jsonl(path, envelope)
    return path


def count_jsonl(path: Path) -> int:
    if not path.exists():
        return 0
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        return sum(1 for line in handle if line.strip())


def summarize_trace_store() -> dict[str, Any]:
    ensure_trace_dirs()
    raw_files = list((TRACE_ROOT / "raw").rglob("*.jsonl"))
    import_manifests = list((TRACE_ROOT / "imports").rglob("IMPORT_MANIFEST.json"))
    normalized_files = list((TRACE_ROOT / "normalized").rglob("*.jsonl"))
    sanitized_files = list((TRACE_ROOT / "sanitized").rglob("*.jsonl"))
    raw_events = sum(count_jsonl(path) for path in raw_files)
    normalized_rows = sum(count_jsonl(path) for path in normalized_files)
    sanitized_rows = sum(count_jsonl(path) for path in sanitized_files)
    imports = []
    for manifest_path in sorted(import_manifests, key=lambda p: p.stat().st_mtime, reverse=True)[:20]:
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception as exc:
            manifest = {"error": repr(exc)}
        imports.append({"path": str(manifest_path), **manifest})
    source_registry = TRACE_ROOT / "registry" / "recommended_sources.json"
    sources = []
    if source_registry.exists():
        try:
            sources = json.loads(source_registry.read_text(encoding="utf-8"))
        except Exception:
            sources = []
    return {
        "root": str(TRACE_ROOT),
        "raw_event_files": len(raw_files),
        "raw_events": raw_events,
        "import_count": len(import_manifests),
        "imports": imports,
        "sanitized_files": len(sanitized_files),
        "sanitized_rows": sanitized_rows,
        "normalized_files": len(normalized_files),
        "normalized_rows": normalized_rows,
        "recommended_sources": sources or PUBLIC_TRACE_SOURCES,
        "updated_at": now_iso(),
    }


def write_recommended_sources() -> Path:
    ensure_trace_dirs()
    path = TRACE_ROOT / "registry" / "recommended_sources.json"
    path.write_text(json.dumps(PUBLIC_TRACE_SOURCES, indent=2), encoding="utf-8")
    return path


def copy_if_exists(src: Path, dst: Path) -> bool:
    if not src.exists():
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return True


def import_fable_phase1(source_root: Path = Path("/mnt/c/projects/fable-trace-lora")) -> dict[str, Any]:
    ensure_trace_dirs()
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    dest = TRACE_ROOT / "imports" / "fable-claude-code" / stamp
    processed_dest = dest / "processed"
    reports_dest = dest / "reports"
    files: list[str] = []

    for name in [
        "claude_style_train.jsonl",
        "claude_style_validation.jsonl",
        "hermes_style_train.jsonl",
        "hermes_style_validation.jsonl",
    ]:
        if copy_if_exists(source_root / "data" / "processed" / name, processed_dest / name):
            files.append(str(processed_dest / name))

    for report in (source_root / "data" / "reports").glob("*"):
        if report.is_file() and copy_if_exists(report, reports_dest / report.name):
            files.append(str(reports_dest / report.name))

    row_counts = {Path(path).name: count_jsonl(Path(path)) for path in files if path.endswith(".jsonl")}
    source_commit = "unknown"
    head = source_root / ".git" / "HEAD"
    if head.exists():
        source_commit = head.read_text(encoding="utf-8", errors="replace").strip()
    manifest = {
        "schema_version": "trace-import-manifest-v1",
        "source": "armand0e/claude-fable-5-claude-code processed by /mnt/c/projects/fable-trace-lora",
        "source_root": str(source_root),
        "source_commit_ref": source_commit,
        "imported_at": now_iso(),
        "destination": str(dest),
        "files": files,
        "row_counts": row_counts,
        "status": "imported_for_internal_phase2_prep",
        "caveats": [
            "Commercial/public reuse blocked pending source license and provider ToS review.",
            "Long training requires Phase 2 masking/render checks before launch.",
            "Hermes-style tool normalization is intended for runtime-shape pretraining, not direct execution replay.",
        ],
    }
    (dest / "IMPORT_MANIFEST.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    append_trace_event("fable-import", {"manifest": manifest}, run_id=stamp)
    return manifest
