def now_iso() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def ensure_trace_dirs() -> None:
    for subdir in TRACE_SUBDIRS:
        (TRACE_ROOT / subdir).mkdir(parents=True, exist_ok=True)


def safe_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8", errors="replace")).hexdigest()[:16]


def scrub_text(text: str, max_chars: int = 120_000) -> tuple[str, int]:
    redactions = 0
    scrubbed = text
    if len(scrubbed) > max_chars:
        scrubbed = scrubbed[:max_chars] + "\n[TRUNCATED]"
        redactions += 1
    for pattern in SECRET_PATTERNS:
        new = pattern.sub("[REDACTED_SECRET]", scrubbed)
        if new != scrubbed:
            redactions += 1
            scrubbed = new
    for pattern, repl in [(WINDOWS_USER_PATH, r"C:\Users\USER"), (WSL_USER_PATH, "/home/USER"), (MNT_USER_PATH, "/mnt/DRIVE/Users/USER")]:
        new = pattern.sub(lambda _m, repl=repl: repl, scrubbed)
        if new != scrubbed:
            redactions += 1
            scrubbed = new
    if "base64" in scrubbed and len(scrubbed) > 2000:
        scrubbed = "[REDACTED_LARGE_BASE64_PAYLOAD]"
        redactions += 1
    return scrubbed, redactions


def scrub_obj(obj: Any) -> tuple[Any, int]:
    if isinstance(obj, str):
        return scrub_text(obj)
    if isinstance(obj, list):
        total = 0
        out = []
        for item in obj:
            cleaned, count = scrub_obj(item)
            out.append(cleaned)
            total += count
        return out, total
    if isinstance(obj, dict):
        total = 0
        out = {}
        for key, value in obj.items():
            cleaned, count = scrub_obj(value)
            out[key] = cleaned
            total += count
        return out, total
    return obj, 0


def append_jsonl(path: Path, row: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def append_trace_event(provider: str, event: dict[str, Any], run_id: str = "manual") -> Path:
    ensure_trace_dirs()
    cleaned, redactions = scrub_obj(event)
    envelope = {
        "schema_version": "agent-trace-event-v1",
        "trace_id": f"trace-{safe_hash(json.dumps(cleaned, sort_keys=True, default=str))}",
        "provider": provider,
        "run_id": run_id,
        "captured_at": now_iso(),
        "redaction_count": redactions,
        "event": cleaned,
    }
    path = TRACE_ROOT / "raw" / provider / run_id / "events.jsonl"
    append_jsonl(path, envelope)
    return path


def count_jsonl(path: Path) -> int:
    if not path.exists():
        return 0
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        return sum(1 for line in handle if line.strip())


def run_command(cmd: list[str], cwd: Path | None = None, timeout_sec: int = 180) -> str:
    proc = subprocess.run(
        cmd,
        cwd=str(cwd) if cwd is not None else None,
        text=True,
        capture_output=True,
        check=False,
        timeout=timeout_sec,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"Command failed: {' '.join(cmd)} ({proc.returncode}) {proc.stderr.strip()}")
    return proc.stdout.strip()


def summarize_trace_store() -> dict[str, Any]:
    ensure_trace_dirs()
    raw_files = list((TRACE_ROOT / "raw").rglob("*.jsonl"))
    import_manifests = list((TRACE_ROOT / "imports").rglob("IMPORT_MANIFEST.json"))
    normalized_files = list((TRACE_ROOT / "normalized").rglob("*.jsonl"))
    sanitized_files = list((TRACE_ROOT / "sanitized").rglob("*.jsonl"))
    sanitized_manifests = list((TRACE_ROOT / "sanitized").rglob("SANITIZED_MANIFEST.json"))
    raw_events = sum(count_jsonl(path) for path in raw_files)
    normalized_rows = sum(count_jsonl(path) for path in normalized_files)
    sanitized_rows = sum(count_jsonl(path) for path in sanitized_files)
    sanitized_imports = []
    for manifest_path in sorted(sanitized_manifests, key=lambda p: p.stat().st_mtime, reverse=True)[:20]:
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception as exc:
            manifest = {"error": repr(exc)}
        sanitized_imports.append({"path": str(manifest_path), **manifest})
    imports = []
    for manifest_path in sorted(import_manifests, key=lambda p: p.stat().st_mtime, reverse=True)[:20]:
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception as exc:
            manifest = {"error": repr(exc)}
        imports.append({"path": str(manifest_path), **manifest})
    source_registry = TRACE_ROOT / "registry" / "recommended_sources.json"
    sources = []
    if source_registry.exists():
        try:
            sources = json.loads(source_registry.read_text(encoding="utf-8"))
        except Exception:
            sources = []
    return {
        "root": str(TRACE_ROOT),
        "raw_event_files": len(raw_files),
        "raw_events": raw_events,
        "import_count": len(import_manifests),
        "imports": imports,
        "sanitized_files": len(sanitized_files),
        "sanitized_rows": sanitized_rows,
        "sanitized_pack_count": len(sanitized_manifests),
        "sanitized_review_files": sum(int(item.get("file_count") or 0) for item in sanitized_imports),
        "sanitized_imports": sanitized_imports,
        "normalized_files": len(normalized_files),
        "normalized_rows": normalized_rows,
        "recommended_sources": sources or PUBLIC_TRACE_SOURCES,
        "updated_at": now_iso(),
    }


